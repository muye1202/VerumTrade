"""Capability envelopes: what a data source actually is and what it can support.

A fallback that returns an LLM-written overview must stay labeled as synthesis; it
must not inherit the evidentiary status of a filing or numeric database.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Literal, TypedDict

SourceClass = Literal["primary_document", "structured_filing_data", "vendor_data", "model_synthesis"]
HistoricalSupport = Literal["point_in_time", "as_reported_current", "current_only", "unknown"]

MODEL_SYNTHESIS_MARKER = "[SOURCE CLASS: model_synthesis]"

# Vendors whose output is generated by a model rather than retrieved from a record.
MODEL_SYNTHESIS_VENDORS = {"openai"}


class SourceEnvelope(TypedDict, total=False):
    provider: str
    source_class: SourceClass
    historical_support: HistoricalSupport
    as_of: str
    retrieved_at: str
    available_fields: list[str]
    missing_fields: list[str]
    notes: list[str]


def build_envelope(
    provider: str,
    source_class: SourceClass,
    historical_support: HistoricalSupport,
    *,
    as_of: str = "",
    available_fields: list[str] | None = None,
    missing_fields: list[str] | None = None,
    notes: list[str] | None = None,
) -> SourceEnvelope:
    return {
        "provider": provider,
        "source_class": source_class,
        "historical_support": historical_support,
        "as_of": as_of,
        "retrieved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "available_fields": list(available_fields or []),
        "missing_fields": list(missing_fields or []),
        "notes": list(notes or []),
    }


def label_model_synthesis(text: str, provider: str) -> str:
    """Prefix model-generated vendor output so every downstream reader sees what it is."""
    body = str(text or "")
    if MODEL_SYNTHESIS_MARKER in body:
        return body
    return (
        f"{MODEL_SYNTHESIS_MARKER} provider={provider}. The text below was written by a language "
        "model from web search results. It is a secondary summary, not a primary document: "
        "do not cite it as a verified fact without the underlying source.\n\n" + body
    )


def is_model_synthesis(text: str) -> bool:
    return MODEL_SYNTHESIS_MARKER in str(text or "")
